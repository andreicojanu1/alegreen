// Secțiunea „Alocare nouă" sub grafic: restrânsă, în timpul extinderii, extinsă, apoi sesiunea cu ID unic.
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://localhost:5173';
const browser = await chromium.launch(process.env.PW_CHROMIUM ? { executablePath: process.env.PW_CHROMIUM } : {});
const page = await browser.newPage({ viewport: { width: 1905, height: 985 } });
page.on('pageerror', (e) => console.error('PAGE ERROR', e.message));
await page.goto(base);
await page.evaluate(() => localStorage.clear());
await page.goto(`${base}/admin/cantitati-colectate`);
const cell = (row, col) => page.locator('tbody tr').nth(row).locator('td').nth(col).locator('input');
await cell(6, 9).fill('400000');
await cell(6, 9).press('Tab');
await page.goto(`${base}/admin/alocari`);
const section = page.getByRole('region', { name: 'Alocare nouă' });
await section.scrollIntoViewIfNeeded();
await page.mouse.wheel(0, 300);
await page.waitForTimeout(300);
await page.screenshot({ path: 'screenshots-out/p6_01_sectiune_restransa.png' });
await page.getByRole('button', { name: 'Alocare nouă' }).click();
await page.waitForTimeout(180);
await page.screenshot({ path: 'screenshots-out/p6_02_in_extindere.png' });
await page.waitForTimeout(700);
await page.screenshot({ path: 'screenshots-out/p6_03_extinsa.png' });
await page.getByRole('button', { name: /Pornește alocarea pentru/ }).click();
await page.waitForTimeout(600);
await page.getByRole('heading', { name: /Alocare Septembrie 2026/ }).scrollIntoViewIfNeeded();
await page.screenshot({ path: 'screenshots-out/p6_04_sesiune_cu_id.png' });
await page.getByRole('tab', { name: 'Istoric rulări' }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: 'screenshots-out/p6_05_istoric_cu_id.png' });
console.log('ok');
await browser.close();
